-- Run once in Supabase SQL Editor.
-- Creates the shared public guestbook table with read/insert-only access.

create table if not exists public.baby_wishes (
  id bigint generated by default as identity primary key,
  name varchar(40) not null,
  message varchar(300) not null,
  created_at timestamptz not null default now()
);

alter table public.baby_wishes enable row level security;

drop policy if exists "Public can read baby wishes" on public.baby_wishes;
create policy "Public can read baby wishes"
on public.baby_wishes for select
to anon
using (true);

drop policy if exists "Public can submit baby wishes" on public.baby_wishes;
create policy "Public can submit baby wishes"
on public.baby_wishes for insert
to anon
with check (
  char_length(trim(name)) between 1 and 40
  and char_length(trim(message)) between 1 and 300
);

grant select, insert on public.baby_wishes to anon;
grant usage, select on sequence public.baby_wishes_id_seq to anon;
